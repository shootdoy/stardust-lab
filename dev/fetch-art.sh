#     ★4    앞면 = **세로 169x300** · 뒷면 = 가로 300x169   ← 실물 카드가 세로다
#   지금 내장 아트(★6·★5 가로 144x81 · ★4 세로 84x149)와 방향이 맞으므로 원본으로 쓸 수 있다.
#   ⚠ «모두 300x169» 라고 적어 두지 말 것 — ★4 를 넣으면서 틀린 서술이 됐다.
#
# ⚠⚠ **기준번호는 추측할 수 없다.** 대체로 연속이지만(…568 → …642) **미라이돈만
#    1776043321** 로 완전히 다른 구간이다. 규칙으로 생성하면 그 한 장을 조용히 놓친다.
#    새 태그를 더할 때는 **목록 페이지에서 번호를 직접 확인해** 아래 표에 적을 것.
#
# ── 아트로 쓸 때 → **`dev/cardcrop.py`**
#   받은 것은 «카드 전체» (흰 테두리·이름띠·에너지 배지 포함) 다. 내장 아트는 «그림만» 이라
#   그대로 넣으면 다른 칸과 모양이 어긋난다. `cardcrop.py` 가 성급별 «그림만» 창으로 잘라
#   `TAGIMG` 를 **제자리 교체**한다 (`artgen.py --force` 는 키가 중복되니 쓰지 말 것).
#   `dev/artcrop.py` 는 **세로 판형(★4 이하) 전용**이라 이 카드에는 쓰지 않는다.
#   ⚠ 이 파일들을 `art_in/` 에 두지 말 것 — `recompress.py` 가 원본으로 알고
#     «카드 전체» 로 다시 인코딩해 v2.4.0 의 «그림만» 크롭을 되돌린다.

