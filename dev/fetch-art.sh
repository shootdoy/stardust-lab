# 탄별 하위 폴더에 둔다 (2026-08-22 잭 지정). 키의 첫 조각이 탄이다 — `1`·`2`·`공통`.
# ⚠ 앱의 키는 «공통-» 이지만 **폴더 이름은 «스페셜»** 이다 (2026-08-22 잭 지정) —
#   레귤러·스페셜 카드에 실제로 찍혀 있는 낱말이 «스페셜» 이기 때문이다.
#   («공통탄» 이 되지 않게 여기서 갈라 준다. 폴더를 «공통» 으로 되돌리지 말 것.)
subdir() {
  case "$1" in
    공통-*) printf '%s/스페셜' "$OUT" ;;
    *)      printf '%s/%s탄' "$OUT" "${1%%-*}" ;;
  esac
}

printf '%s\n' "$TAGS" | while IFS=$'\t' read -r n key code nback; do
  [ -n "$n" ] || continue
  sub=$(subdir "$key"); mkdir -p "$sub" || exit 1
  # 파일명은 **카드에 찍힌 코드**를 앞에 둔다 — `1-1-007-미라이돈-앞.png` (2026-08-22 잭 지정).
  # 코드로 앱 데이터를 조회하면 성급까지 나오므로 `dev/cardcrop.py` 가 창을 고를 수 있다.
  # ⚠ 파일명에 성급을 넣지 않는다 — 코드가 정본이고, 이름을 눈으로 읽을 일이 없어진다.
  name="${key#*-}"; name="${name#*-}"          # «1-6-미라이돈» → «미라이돈»
  for pair in "9:앞" "10:뒤"; do
    suf="${pair%%:*}"; face="${pair##*:}"
    # 뒷면 기준번호가 따로 적혀 있으면 그것을 쓴다 (샤미드처럼 앞·뒤가 다른 태그)
    base="$n"
    [ "$face" = "뒤" ] && [ -n "${nback:-}" ] && base="$nback"
    dst="$sub/$code-$name-$face.png"
    if [ -s "$dst" ] && [ "$FORCE" = 0 ]; then
      echo "  건너뜀  $code-$name-$face"
      continue
    fi
    tmp="$dst.part"
    hc=$(curl -sSL --max-time 30 -o "$tmp" -w '%{http_code}' "$BASE_URL/$base$suf.png")
    if [ "$hc" != "200" ] || [ ! -s "$tmp" ]; then
      rm -f "$tmp"; echo "  ★ 실패   $code-$name-$face (HTTP $hc)"; continue
    fi
    # PNG 인지 확인한다 — 오류 페이지를 200 으로 주는 경우가 있다
    if ! file -b "$tmp" | grep -q '^PNG image'; then
      rm -f "$tmp"; echo "  ★ PNG 아님 $code-$name-$face"; continue
    fi
    mv "$tmp" "$dst"
    printf '  받음    %-22s %s\n' "$code-$name-$face" "$(file -b "$dst" | grep -oE '[0-9]+ x [0-9]+')"
  done
done

