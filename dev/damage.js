/* ══ 대기 피격 곡선 ══ */
// 대기 피해는 «절대 HP 포인트»이고 f 의 매우 완만한 함수다. 거듭제곱 지수를 스윕해 적합한다.
// 2026-08-12: 표본 12건에서 최적 지수 ≈0.38 (√f=0.5 는 RMS 12% → 0.38 은 9%).
// 결정적 근거 — 같은 대상 가이오가 쌍: f 90→377 (4.2배)에 피해 19.2%→26.0% (1.35배).
//   √f 라면 2.05배여야 한다. 선형은 RMS 43% 로 완전히 기각.
// n=1/3(세제곱근)과 0.38 은 오차 내라 아직 미분리. f 극단(1200+ 또는 50 이하) 표본이 필요하다.
console.log('\n대기 피격 곡선 — 피해pt(실측%xHP) vs 공격 강도 f');
const Wd=SAMPLES.filter(s=>s.wait).map(s=>{
  const A=POOL.find(p=>p.id===s.atk), T=POOL.find(p=>p.id===s.tgt);
  const m=A.mv.find(x=>x.n===s.move);
  const atk=(m.k==='물리'?A.a:A.sa), def=(m.k==='물리'?T.d:T.sd);
  const f=(POWER[m.n]??100)*(atk+s.bonus)/def*(s.mult??eff(m.t,T.t))*(s.xfac??1);
  return {lab:s.lab, mode:s.mode||'?', f, pts:s.meas/100*T.hp, hp:T.hp, eye:/육안/.test(s.note)};
}).sort((a,b)=>a.f-b.f);
const rms=fn=>Math.sqrt(Wd.reduce((a,w)=>a+Math.pow(w.pts/fn(w)-1,2),0)/Wd.length)*100;
const fitPow=n=>{const c=Wd.reduce((a,w)=>a+w.pts/Math.pow(w.f,n),0)/Wd.length;
  return {n,c,rms:rms(w=>c*Math.pow(w.f,n))};};
let best=fitPow(0.5);
for(let n=0.20;n<=0.80;n+=0.01){const r=fitPow(n); if(r.rms<best.rms)best=r;}
console.log('  모델 비교 (RMS 잔차):');
for(const n of [1/3,best.n,0.5,1.0]){const r=fitPow(n);
  console.log('    pt='+r.c.toFixed(3)+'xf^'+n.toFixed(2)+(Math.abs(n-best.n)<1e-9?'  ← 최적':'')+'   RMS '+r.rms.toFixed(1)+'%');}
console.log('  HP 비율 모델(대조): RMS '+(()=>{const k=Wd.reduce((a,w)=>a+(w.pts/w.hp)/Math.sqrt(w.f),0)/Wd.length;
  return rms(w=>k*Math.sqrt(w.f)*w.hp);})().toFixed(1)+'%  — 절대 pt 가 우세, 고HP 대상 가설은 기각');
console.log('');
for(const w of Wd){
  const p=best.c*Math.pow(w.f,best.n);
  console.log('  '+w.mode.padEnd(4)+w.lab.padEnd(24)+' f='+String(Math.round(w.f)).padStart(4)
    +'  실측 '+w.pts.toFixed(1)+'pt('+(w.pts/w.hp*100).toFixed(0)+'%)'
    +'  적합 '+p.toFixed(1)+'  잔차 '+((w.pts/p-1)*100).toFixed(0)+'%'+(w.eye?'  [육안]':''));
}
 